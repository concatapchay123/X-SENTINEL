client = TestClient(app)


def _is_mssql_connected() -> bool:
    try:
        engine = create_engine(settings.database_url)
        with engine.connect() as conn:
            conn.execute(Base.metadata.tables["analysis_jobs"].select().limit(1))
        engine.dispose()
        return True
    except Exception:
        return False


mssql_available = _is_mssql_connected()


@pytest.fixture
def integration_sqlite_db() -> Session:
    """Isolated thread-safe SQLite in-memory database."""
    engine = create_engine(
        "sqlite:///:memory:",
        connect_args={"check_same_thread": False},
        poolclass=StaticPool,
    )
    for col in Base.metadata.tables["audit_events"].columns:
        if col.name == "id":
            from sqlalchemy import Integer
            col.type = Integer()
    for table in Base.metadata.tables.values():
        for col in table.columns:
            if col.server_default is not None:
                text_str = str(col.server_default.arg)
                if "N'" in text_str:
                    col.server_default.arg.text = text_str.replace("N'", "'")
    Base.metadata.create_all(engine)
    session = Session(engine)
    try:
        yield session
    finally:
        session.close()
        engine.dispose()


class TestEndToEndCoreApiIntegration:
    """Verifies complete end-to-end user workflows through the Core REST API."""

    def test_full_analysis_history_alert_evidence_workflow(
        self, integration_sqlite_db: Session
    ) -> None:
        def _get_db_override():
            yield integration_sqlite_db

        app.dependency_overrides[get_db] = _get_db_override
        try:
            # 1. Analyze vector with high feature to trigger ALERT
            req_id = f"req-flow-{uuid.uuid4()}"
            vector = [0.0] * 2381
            vector[0] = 75.0
            vector[1] = 50.0

            resp_post = client.post(
                "/v1/analyze/vector",
                json={"features": vector, "request_id": req_id},
            )
            assert resp_post.status_code == 200
            post_data = resp_post.json()
            assert post_data["request_id"] == req_id
            job_id = post_data["job_id"]
            ev_hash = post_data["evidence_ref"]
            assert job_id is not None
            assert ev_hash is not None

            # 2. History listing reflects the new job
            resp_hist = client.get("/v1/analysis")
            assert resp_hist.status_code == 200
            hist_data = resp_hist.json()
            assert hist_data["total"] >= 1
            matching = [j for j in hist_data["items"] if j["id"] == job_id]
            assert len(matching) == 1
            assert matching[0]["request_id"] == req_id

            # 3. Retrieve analysis details
            resp_detail = client.get(f"/v1/analysis/{job_id}")
            assert resp_detail.status_code == 200
            detail_data = resp_detail.json()
            assert detail_data["id"] == job_id
            assert detail_data["request_id"] == req_id
            assert len(detail_data["scores"]) == 5
            assert detail_data["result"] is not None

            # 4. Verify alerts generated by analysis
            resp_alerts = client.get(f"/v1/alerts?analysis_job_id={job_id}")
            assert resp_alerts.status_code == 200
            alerts_data = resp_alerts.json()
            assert alerts_data["total"] >= 1
            alert_id = alerts_data["items"][0]["id"]
            assert alerts_data["items"][0]["status"] == "open"

            # 5. Lifecycle transitions: open -> acknowledged
            resp_ack = client.patch(
                f"/v1/alerts/{alert_id}",
                json={"status": "acknowledged"},
            )
            assert resp_ack.status_code == 200
            assert resp_ack.json()["status"] == "acknowledged"

            # 6. Lifecycle transition: acknowledged -> resolved
            resp_res = client.patch(
                f"/v1/alerts/{alert_id}",
                json={"status": "resolved"},
            )
            assert resp_res.status_code == 200
            assert resp_res.json()["status"] == "resolved"
            assert resp_res.json()["resolved_at"] is not None

            # 7. Evidence retrieval and integrity check
            resp_ev = client.get(f"/v1/analysis/{job_id}/evidence")
            assert resp_ev.status_code == 200
            ev_data = resp_ev.json()
            assert ev_data["evidence_hash"] == ev_hash
            assert ev_data["verified"] is True
            assert ev_data["request_id"] == req_id

            # 8. Tamper with evidence record in database
            parsed_job_uuid = uuid.UUID(job_id)
            res_rec = integration_sqlite_db.get(AnalysisResultRecord, parsed_job_uuid)
            assert res_rec is not None
            tampered = dict(res_rec.result_json)
            tampered["malware_score"] = 0.999
            res_rec.result_json = tampered
            integration_sqlite_db.commit()

            # Read-back must fail with 409
            resp_tampered = client.get(f"/v1/analysis/{job_id}/evidence")
            assert resp_tampered.status_code == 409
            assert resp_tampered.json()["detail"]["code"] == "XS_EVIDENCE_INTEGRITY_MISMATCH"

        finally:
            app.dependency_overrides.clear()

    @pytest.mark.skipif(not mssql_available, reason="live Microsoft SQL Server not reachable")
    def test_live_mssql_api_integration_workflow(self) -> None:
        """Full analysis, history, alert, evidence workflow against live SQL Server."""
        # Using real get_db without overrides
        req_id = f"req-mssql-flow-{uuid.uuid4()}"
        vector = [0.0] * 2381
        vector[0] = 80.0
        vector[1] = 60.0

        resp_post = client.post(
            "/v1/analyze/vector",
            json={"features": vector, "request_id": req_id},
        )
        assert resp_post.status_code == 200
        post_data = resp_post.json()
        job_id = post_data["job_id"]
        ev_hash = post_data["evidence_ref"]
        assert job_id is not None

        try:
            # Query history
            resp_hist = client.get(f"/v1/analysis/{job_id}")
            assert resp_hist.status_code == 200
            assert resp_hist.json()["id"] == job_id

            # Query evidence
            resp_ev = client.get(f"/v1/analysis/{job_id}/evidence")
            assert resp_ev.status_code == 200
            assert resp_ev.json()["evidence_hash"] == ev_hash
            assert resp_ev.json()["verified"] is True

            # Query alerts
            resp_alerts = client.get(f"/v1/alerts?analysis_job_id={job_id}")
            assert resp_alerts.status_code == 200
            items = resp_alerts.json()["items"]
            if items:
                alert_id = items[0]["id"]
                resp_patch = client.patch(f"/v1/alerts/{alert_id}", json={"status": "acknowledged"})
                assert resp_patch.status_code == 200
                assert resp_patch.json()["status"] == "acknowledged"

        finally:
            # Cleanup test record from real SQL Server
            engine = create_engine(settings.database_url)
            with Session(engine) as cleanup_sess:
                job_uuid = uuid.UUID(job_id)
                job_record = cleanup_sess.get(AnalysisJob, job_uuid)
                if job_record:
                    cleanup_sess.delete(job_record)
                    cleanup_sess.commit()
            engine.dispose()
